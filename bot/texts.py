def user_id(value):
    return f'Telegram User ID: <code>{value}</code>'


def page_number(value):
    return f'Страница {value}'


def lead(row, updated=False):
    name = ' '.join(filter(None, (row['first_name'], row['last_name']))) or 'Пользователь'
    username = row['username']
    url = f'https://t.me/{username}' if username else f"tg://user?id={row['telegram_user_id']}"
    contact = '@' + username if username else name
    date = datetime.fromisoformat(row['updated_at']).astimezone(MOSCOW)
    title = '📝 Пользователь обновил заявку на мини-радар' if updated else '🔔 Новая заявка на мини-радар!'
    return (f'<b>{title}</b>\n\n👤 <b>Пользователь:</b> {escape(name)}\n'
            f'🔗 <b>Telegram:</b> <a href="{escape(url, quote=True)}">{escape(contact)}</a>\n'
            f"🆔 <b>Telegram ID:</b> {row['telegram_user_id']}\n\n"
            f"💼 <b>Ниша бизнеса:</b>\n{escape(row['business_niche'])}\n\n"
            f"🎯 <b>Целевая аудитория:</b>\n{escape(row['target_audience'])}\n\n"
            f"📅 <b>Дата:</b> {date:%d.%m.%Y, %H:%M} (МСК)\n"
            f"<b>Заявка №{row['id']}</b> · Статус: {row['status']}")


